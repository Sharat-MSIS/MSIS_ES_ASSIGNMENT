/*
 * EXTI interrupt callback
 *
 * This function is automatically called by:
 *
 * EXTI15_10_IRQHandler()
 *          ↓
 * HAL_GPIO_EXTI_IRQHandler()
 *          ↓
 * HAL_GPIO_EXTI_Callback()
 *
 * No need to call this function from main().
 */
void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
    /*
     * Check whether the interrupt came from PC13.
     *
     * This is important when multiple GPIO pins
     * are configured as EXTI.
     */
    if (GPIO_Pin == EXTI_BUTTON_Pin)
    {
        /*
         * Get the current system time in milliseconds.
         */
        uint32_t currentTime = HAL_GetTick();


        /*
         * Switch debounce
         *
         * Check whether enough time has passed since
         * the previous valid button press.
         *
         * If less than 100 ms has passed, the interrupt
         * is considered switch bounce and is ignored.
         */
        if ((currentTime - lastPressTime) >= DEBOUNCE_TIME)
        {
            /*
             * A valid button press has been detected.
             *
             * Move to the next LED pattern.
             */
            presscount++;


            /*
             * Keep presscount between 0 and 3.
             *
             * Sequence:
             *
             * 0 → 1 → 2 → 3 → 0 → 1 → ...
             */
            presscount = presscount % 4;


            /*
             * Store the time of this valid button press.
             *
             * This time is used for debouncing the next press.
             */
            lastPressTime = currentTime;
        }
    }
}
